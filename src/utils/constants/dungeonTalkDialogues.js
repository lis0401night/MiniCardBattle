/**
 * コンテキスト情報から優先表示すべき会話カテゴリキーを判定する
 * @param {Object} context - { floor, hp, deckSize }
 * @returns {string} コンテキストキー（CONTEXT_PRE_BOSS等）またはCONTEXT_NORMAL
 */
function resolveContextKey(context) {
  const { floor, hp } = context;

  // 優先度1: ボス関連（3種は同一優先度、同時成立しないため先に該当した方を返す）
  // これから挑む階が高難易度ボス階（50の倍数）
  if (floor % HIGH_BOSS_CYCLE === 0) {
    return CONTEXT_PRE_HIGH_BOSS;
  }
  // これから挑む階がボス階（10の倍数）
  if (floor % BOSS_CYCLE === 0) {
    return CONTEXT_PRE_BOSS;
  }
  // ボス撃破直後（直前の階がボスだった = これから挑む階が10の倍数+1、かつ1階ではない）
  if (floor > 1 && (floor - 1) % BOSS_CYCLE === 0) {
    return CONTEXT_POST_BOSS;
  }

  // 優先度2: HP ≤ 5
  if (hp <= HP_CRITICAL_THRESHOLD) {
    return CONTEXT_LOW_HP;
  }
  // 優先度3: 5 < HP ≤ 10
  if (hp <= HP_WARNING_THRESHOLD) {
    return CONTEXT_WARN_HP;
  }

  // 優先度4: 通常
  return CONTEXT_NORMAL;
}

/**
 * テンプレート変数を置換するヘルパー
 * @param {string} text - 台詞テキスト
 * @param {Object} context - { floor, hp, deckSize }
 * @returns {string} 置換済みテキスト
 */
