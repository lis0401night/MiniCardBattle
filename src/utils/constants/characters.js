/**
 * 指定したキャラクター・スキン・タイプに応じた画像パスを取得する
 * @param {string|Object} charIdOrObj - キャラクターIDまたはキャラクターオブジェクト
 * @param {string} skinId - スキンID ('default', 'summer' etc.)
 * @param {string} type - 画像タイプ ('image', 'imageLose', 'icon', 'iconDamage')
 * @returns {string} 画像パス
 */
export function getSkinImage(charIdOrObj, skinId = 'default', type = 'image') {
  const char =
    typeof charIdOrObj === 'string' ? CHARACTERS[charIdOrObj] : charIdOrObj;
  if (!char) return '';

  const getRawPath = () => {
    if (!char.skins) return char[type] || '';
    const skin = char.skins[skinId] || char.skins['default'];
    return skin[type] || char[type] || '';
  };

  const path = getRawPath();
  return path ? appendVersionQuery(path) : '';
}

export const BOSS_CHARACTER_IDS = ['void', 'succubus', 'warlock', 'satan'];

export const RED_FRAME_CHARACTERS = BOSS_CHARACTER_IDS;

/**
 * プレイヤーのプロフィール画像パスを決定する共通関数
 * @param {Object} player - プレイヤーデータ { icon, skin, ... }
 * @returns {string} 画像パス
 */
export function getPlayerIconPath(player) {
  if (player && player.icon) {
    return appendVersionQuery(`assets/icons/icon_${player.icon}.webp`);
  }
  return appendVersionQuery('assets/icons/icon_player.webp');
}

/**
 * プレイヤーのアイコン枠（赤/金）の種類を決定する共通関数
 * @param {string} charId - キャラクターID
 * @returns {string} 'red' または 'gold'
 */
export function getPlayerIconFrame(charId) {
  return RED_FRAME_CHARACTERS.includes(charId) ? 'red' : 'gold';
}

/**
 * プレイヤーのアイコン枠の画像パスを決定する共通関数（キャッシュバスティング対応）
 * @param {string} charId - キャラクターID
 * @returns {string} 画像パス
 */
export function getIconFramePath(charId) {
  const frame = getPlayerIconFrame(charId);
  return appendVersionQuery(`assets/icons/iconframe_${frame}.webp`);
}

/**
 * プレイヤーのアイコン画像からキャラクターを決定し、そのテーマカラーを取得する共通関数
 * @param {Object} player - プレイヤーデータ { icon, character, ... }
 * @returns {string} カラーコード (e.g. '#38bdf8')
 */
export function getPlayerColor(player) {
  if (player && player.icon && player.icon !== 'player') {
    const baseId = player.icon.split('_')[0];
    const char = CHARACTERS[baseId];
    if (char && char.color) {
      return char.color;
    }
  }
  return '#ffffff';
}
