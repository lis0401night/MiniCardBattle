  arm_self: 14, // 武装: 他のカードを上書き配置できる（1回限定）
  seal: 12, // 結界: レーン封印で相手の展開を制限

  // === 10pt: 中価値・同等のスキル ===
  phase: 10, // 位相: 敵をすり抜けて相手リーダーを直接攻撃できる強力なフィニッシャー能力
  grave_keeper: 10, // 墓守: 墓地参照系（復活・代価など）を封殺する妨害型パッシブ
  miasma: 10, // 瘴気: 回復効果（HP回復アクティブ・ドレイン等）を反転ダメージ化する妨害型パッシブ
