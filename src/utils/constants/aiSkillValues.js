/**
 * Mini Card Battle - AIスキルユーティリティ価値定義
 *
 * AIの盤面評価関数（evaluateSimState）で使用するスキルごとの価値を定義する。
 * 値が大きいほどAIがそのスキルを持つカードの配置を高く評価する。
 *
 * ※ ここで定義するのは「場に残っているカードが持つスキルの継続的な価値」である。
 *   召喚時に即発動するアクティブスキル（snipe, spread等）は
 *   シミュレーション内で効果が盤面に反映されるため、ここでは扱わない。
 *
 * 優先順位（降順）:
 * 頑丈 > 必殺 > 祝福 > 分裂 > 魂縛 > 変化 > 報復 > 連撃 > 吸収 > 簒奪 > 結界 > 回復 > 入替 > 攪乱
 */

// スキルIDごとのユーティリティ価値
export const AI_SKILL_UTILITY = {
  // === 高価値: 戦闘に直接大きな影響を与えるスキル ===
  sturdy: 30, // 頑丈: ダメージ半減で実質的にパワー2倍の耐久力
  deadly: 28, // 必殺: 戦闘時に確定破壊、パワー差を無効化する最強の戦闘スキル

  // === 中高価値: アドバンテージを生むスキル ===
  bless: 25, // 祝福: 手札のパワー増強で後続の展開を強化
  split: 22, // 分裂: 破壊時にトークンを残し盤面を維持
  soul_bind: 20, // 魂縛: 戦闘破壊ごとにパワー増加、スノーボール効果
  morph: 18, // 変化: 相手の手札を劣化させるハンドアドバンテージ破壊

  // === 中価値: 戦闘補助や継続的効果 ===
  retaliate: 16, // 報復: 味方の破壊をトリガーにパワー増加
  double_strike: 15, // 連撃: 戦闘ダメージ2倍で突破力向上
  absorb: 14, // 吸収: 戦闘ダメージの半分をリーダー回復
  extort: 13, // 簒奪: リーダーダメージ時に相手の手札を劣化

  // === 低中価値: 状況依存の効果 ===
  seal: 12, // 結界: レーン封印で相手の展開を制限
  heal: 10, // 回復: リーダーHP回復
  draw: 8, // 入替: 手札の入れ替えで質を向上

  // === 低価値: 特殊な状況で有効 ===
  shuffle: 5, // 攪乱: 互いの手札リセット、ランダム性が高い

  // === 動的評価スキル ===
  hack: (state, GameState) => {
    // 結果的に相手(AI)の方がSPが増えるなら+21、減る（または変わらない）なら0
    if ((state.enemySP || 0) > (GameState.enemySP || 0)) {
      return 21;
    }
    return 0;
  },
};
