  split: 23, // 分裂: 破壊時にトークンを残し盤面を維持
  absorb: 22, // 吸収: 戦闘ダメージの半分をリーダー回復
  extort: 21, // 簒奪: リーダーダメージ時に相手の手札を劣化
  soul_bind: 20, // 魂縛: 戦闘破壊ごとにパワー増加、スノーボール効果
  retaliate: 20, // 報復: 味方の破壊をトリガーにパワー増加

  // === 19～10pt: 中高価値・自己強化・防御・妨害スキル ===
  morph: 19, // 変化: 相手の手札を劣化させるハンドアドバンテージ破壊
  bless: 28, // 祝福: 手札のパワー増強で後続の展開を強化
