/**
 * 試練の宮殿導入会話のダイアログキューを組み立てる
 * @param {Object} deckData - selectRentalDeck で受け取るデッキデータオブジェクト
 *   - isCharacterLeader: boolean — 通常キャラクターリーダーか
 *   - isCardLeader: boolean — カードリーダーか
 *   - leaderId: string — リーダーのID
 *   - name: string — リーダー名
 *   - icon: string — アイコン画像パス
 *   - image: string — 画像パス
 *   - originalData: Object — 元の敵データ（leaderCardId等を含む）
 * @returns {Array} ダイアログノード配列
 */
export function buildDungeonIntroDialogue(deckData) {
  const leaderName = deckData.name || deckData.originalData?.name || 'リーダー';
  const leaderImage =
    deckData.image ||
    deckData.icon ||
    deckData.originalData?.image ||
    deckData.originalData?.icon;

  if (deckData.isCharacterLeader) {
    // ============================================================
    // パターンA：通常キャラクターリーダー
    // ============================================================
    const charId = deckData.leaderId;
    const lines =
      DUNGEON_INTRO_CHARACTER_LINES[charId] ||
      DUNGEON_INTRO_CHARACTER_LINES.android;

    // キャラクター台詞ノードを組み立て
    const characterNodes = lines.map((text) => ({
      speaker: 'player',
      speakerName: leaderName,
      text: text,
      leftImage: leaderImage,
      centerMode: true,
    }));

    return [
      ...COMMON_NARRATION_OPENING,
      ...characterNodes,
      CHARACTER_LEADER_CLOSING,
    ];
  } else {
    // ============================================================
    // パターンB：カードリーダー（ボイスカテゴリ別）
    // ============================================================
    const voiceCategory = resolveVoiceCategory(deckData);
    const lines =
      DUNGEON_INTRO_CARD_LEADER_LINES[voiceCategory] ||
      DUNGEON_INTRO_CARD_LEADER_LINES.default;

    // カードリーダー台詞ノードを組み立て
    const leaderNodes = lines.map((text) => ({
      speaker: 'player',
      speakerName: leaderName,
      text: text,
      leftImage: leaderImage,
      centerMode: true,
    }));

    return [
      ...COMMON_NARRATION_OPENING,
      CARD_LEADER_STRAY_NARRATION,
      ...leaderNodes,
      CARD_LEADER_CLOSING,
    ];
  }
}

/**
 * カードリーダーのボイスカテゴリを解決するヘルパー
 * deckData.originalData.leaderCardId → CARD_MASTER の voiceCategory を参照
 * @param {Object} deckData - デッキデータ
 * @returns {string} ボイスカテゴリID
 */
function resolveVoiceCategory(deckData) {
  const leaderCardId = deckData.originalData?.leaderCardId;
  if (!leaderCardId) return 'default';

  const cardData = CARD_MASTER.find((c) => c.id === leaderCardId);
  if (cardData && cardData.voiceCategory) {
    return cardData.voiceCategory;
  }

  return 'default';
}
